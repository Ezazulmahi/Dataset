"""Collect every number that main.tex takes from the re-embedding and steganalysis runs,
write numbers.tex, patch the detectability rows into main.tex, and draw Figure 4."""
import numpy as np, pandas as pd, re, os
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.metrics import roc_curve, roc_auc_score
import common as C

plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 7, "axes.linewidth": 0.6, "pdf.fonttype": 42,
                     "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False})
BLUE, ORANGE, AQUA, VIOLET, INK, GRID = "#2a78d6", "#eb6834", "#1baf7a", "#4a3aa7", "#30363d", "#d9dde1"

# ------------------------------------------------------------------ re-embedding run
e = pd.read_csv("embed_rerun.csv")
ft = e[e.set == "ft"]; bs = e[e.set == "base"]
COMPLETE = len(ft) == 400 and len(bs) == 400
print("re-embedding run complete:", COMPLETE, len(ft), len(bs))
print("errors:", e.error.dropna().unique())
print("exact recovery  ft %d/400  base %d/400 ; max BER ft %s base %s" % (ft.exact.sum(), bs.exact.sum(), ft.ber.max(), bs.ber.max()))
lo = lambda d: d[(d.bpp >= 0.30) & (d.bpp < 0.40)]; hi = lambda d: d[d.bpp >= 0.50]
macros = {
    "RecFT": f"{int(ft.exact.sum())} of 400", "RecBase": f"{int(bs.exact.sum())} of 400",
    "FixMedFT": f"{int(ft.fix_passes.median())}", "FixMaxFT": f"{int(ft.fix_passes.max())}",
    "FixMedBase": f"{int(bs.fix_passes.median())}", "FixMaxBase": f"{int(bs.fix_passes.max())}",
    "PSNRcolFT": f"${ft.psnr_color.mean():.2f}\\pm{ft.psnr_color.std():.2f}$", "PSNRcolBase": f"${bs.psnr_color.mean():.2f}\\pm{bs.psnr_color.std():.2f}$",
    "EmbLowFT": f"{lo(ft).embed_s.median():.0f}", "EmbHighFT": f"{hi(ft).embed_s.median():.0f}",
    "ExtMed": f"{e.extract_s.median():.2f}",
}
if not COMPLETE:      # provisional file so that main.tex compiles while the run is still in progress
    macros = {k: "\\textcolor{red}{\\textbf{[pending: re-embedding run in progress]}}" for k in macros}
with open("../numbers.tex", "w", encoding="utf-8") as f:
    f.write("% generated by analysis/final_numbers.py -- do not edit by hand\n")
    for k, v in macros.items():
        f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print(macros)
rt = []
for lab, sel in (("0.30--0.40", lambda d: d[d.bpp < 0.40]), ("0.40--0.50", lambda d: d[(d.bpp >= 0.40) & (d.bpp < 0.50)]), ("0.50--0.60", lambda d: d[d.bpp >= 0.50])):
    for tag, d in (("Fine-tuned", ft), ("Baseline", bs)):
        s = sel(d); rt.append((lab, tag, len(s), s.embed_s.median(), s.embed_s.quantile(.25), s.embed_s.quantile(.75), s.embed_s.max(), s.fix_passes.median(), s.extract_s.median()))
rt = pd.DataFrame(rt, columns=["bpp", "covers", "n", "embed_med", "q25", "q75", "max", "fix_med", "extract_med"]); rt.to_csv("runtime_table.csv", index=False); print(rt.round(2).to_string())
# agreement of the re-run with the authors' spreadsheet (different messages, same K and length)
cmp_ = pd.read_excel(C.RES + r"\comparison_results.xlsx", sheet_name="per_image_results").set_index("image")
m = ft.set_index("image").join(cmp_[["finetuned_psnr", "finetuned_ssim", "baseline_psnr", "baseline_ssim", "K"]], rsuffix="_a")
print("re-run vs authors, fine-tuned PSNR_Y: mean abs diff %.3f dB ; SSIM %.4f" % ((m.psnr_luma - m.finetuned_psnr).abs().mean(), (m.ssim_luma - m.finetuned_ssim).abs().mean()))
mb = bs.set_index("image").join(cmp_[["baseline_psnr", "baseline_ssim"]])
print("re-run vs authors, baseline PSNR_Y: mean abs diff %.3f dB ; SSIM %.4f" % ((mb.psnr_luma - mb.baseline_psnr).abs().mean(), (mb.ssim_luma - mb.baseline_ssim).abs().mean()))
cs = pd.read_csv("cover_stats.csv"); f_ = cs[cs.set == "ft"].set_index("image"); b_ = cs[cs.set == "base"].set_index("image")
print("forced K > adaptive K (fine-tuned):", int((cmp_.K.reindex(f_.index) > f_.K).sum()), "of 400")
print("baseline cover-derived capacity range: %.4f-%.4f ; >=0.30: %d of %d" % (b_.capacity_bpp[~b_.fallback].min(), b_.capacity_bpp[~b_.fallback].max(), (b_.capacity_bpp[~b_.fallback] >= 0.30).sum(), (~b_.fallback).sum()))
print("fine-tuned capacity >=0.30:", int((f_.capacity_bpp >= 0.30).sum()), " ratio cover-derived means %.1f" % (f_.capacity_bpp.mean() / b_.capacity_bpp[~b_.fallback].mean()))

# ------------------------------------------------------------------ detectability rows
st = pd.concat([pd.read_csv("steganalysis_spam.csv"), pd.read_csv("steganalysis_generic_dct.csv")], ignore_index=True); print(st[["experiment", "PE", "AUC", "AUC_lo", "AUC_hi"]].round(3).to_string())
s = pd.read_excel(C.RES + r"\steganalysis_results.xlsx", sheet_name="per_image_detection")
y = np.r_[np.zeros(len(s)), np.ones(len(s))]; sc = np.r_[s.cover_pct_stego, s.stego_pct_stego] / 100
fpr, tpr, _ = roc_curve(y, sc); pe_cnn = ((fpr + 1 - tpr) / 2).min(); auc_cnn = roc_auc_score(y, sc)
rng = np.random.default_rng(0); bsamp = []
for _ in range(2000):
    ix = rng.integers(0, len(s), len(s)); bsamp.append(roc_auc_score(y, np.r_[s.cover_pct_stego.values[ix], s.stego_pct_stego.values[ix]]))
cnn_lo, cnn_hi = np.percentile(bsamp, [2.5, 97.5])
def row(emb, cov, det, pe, auc, lo_, hi_):
    return f"{emb} & {cov} & {det} & {pe:.3f} & {auc:.3f} ({lo_:.3f}--{hi_:.3f}) \\\\"
g = lambda key: st[st.experiment == key].iloc[0]
rows = [row("DEDS", "fine-tuned", "CNN, SRNet-style (DEDS on photographs)", pe_cnn, auc_cnn, cnn_lo, cnn_hi)]
spec = [("DEDS embedder, fine-tuned covers (matched detector)", "DEDS", "fine-tuned", "SPAM (DEDS, same source)"),
        ("DEDS embedder, baseline covers (matched detector)", "DEDS", "baseline", "SPAM (DEDS, same source)"),
        ("DEDS embedder, fine-tuned covers (detector trained on S-UNIWARD)", "DEDS", "fine-tuned", "SPAM (S-UNIWARD, same source)"),
        ("DEDS embedder, fine-tuned covers (detector trained on LSB matching)", "DEDS", "fine-tuned", "SPAM (LSB matching, same source)"),
        ("DEDS embedder, fine-tuned covers (detector trained on generic DCT, 5-15% rate)", "DEDS", "fine-tuned", "SPAM (generic DCT LSB, same source)"),
        ("S-UNIWARD, fine-tuned covers (matched detector)", "S-UNIWARD", "fine-tuned", "SPAM (S-UNIWARD, same source)"),
        ("S-UNIWARD, baseline covers (matched detector)", "S-UNIWARD", "baseline", "SPAM (S-UNIWARD, same source)"),
        ("LSB matching, fine-tuned covers (matched detector)", "LSB matching", "fine-tuned", "SPAM (LSB matching, same source)"),
        ("LSB matching, baseline covers (matched detector)", "LSB matching", "baseline", "SPAM (LSB matching, same source)")]
for key, emb, cov, det in spec:
    if (st.experiment == key).any():
        r = g(key); rows.append(row(emb, cov, det, r.PE, r.AUC, r.AUC_lo, r.AUC_hi))
    if key.startswith("DEDS embedder, fine-tuned covers (detector trained on generic DCT"):
        rows.append("\\midrule")
open("table3_rows.tex", "w", encoding="utf-8").write("\n".join(rows) + "\n")
tex = open("../main.tex", encoding="utf-8").read()
a = tex.index("%T3START") if "%T3START" in tex else None
if a is None:
    tex = tex.replace("\\input{table3_rows}", "%T3START\n" + "\n".join(rows) + "\n%T3END")
else:
    b = tex.index("%T3END"); tex = tex[:a] + "%T3START\n" + "\n".join(rows) + "\n" + tex[b:]
open("../main.tex", "w", encoding="utf-8").write(tex)
print("\n".join(rows)); print("CNN pooled: PE %.3f AUC %.3f [%.3f, %.3f]" % (pe_cnn, auc_cnn, cnn_lo, cnn_hi))

# ------------------------------------------------------------------ Figure 4
d = cmp_.reset_index()
fig, axes = plt.subplots(1, 3, figsize=(7.2, 2.7), gridspec_kw={"wspace": 0.36, "width_ratios": [1, 1, 1.15]})
edges = np.arange(0.30, 0.601, 0.05); mid = (edges[:-1] + edges[1:]) / 2
for ax, col, yl, ttl in ((axes[0], "psnr", "luminance PSNR (dB)", "a"), (axes[1], "ssim", "luminance SSIM", "b")):
    for tag, c, lab, mk in (("baseline", BLUE, "baseline covers", "o"), ("finetuned", ORANGE, "fine-tuned covers", "s")):
        ax.scatter(d.achieved_bpp, d[f"{tag}_{col}"], s=3, color=c, alpha=0.28, lw=0)
        mu = [d[(d.target_bpp >= a_) & (d.target_bpp < b_ + 1e-9)][f"{tag}_{col}"].mean() for a_, b_ in zip(edges[:-1], edges[1:])]
        ax.plot(mid, mu, color=c, lw=1.5, marker=mk, ms=3.5, mec="white", mew=0.6, label=lab)
    ax.set_xlabel("embedded payload (bits per pixel)"); ax.set_ylabel(yl); ax.grid(color=GRID, lw=0.5); ax.set_axisbelow(True)
    ax.set_title(ttl, loc="left", fontsize=8.5, fontweight="bold"); ax.legend(fontsize=6, loc="lower left" if col == "ssim" else "upper right")
ax = axes[2]
z = np.load("steganalysis_spam_scores.npz", allow_pickle=True); names = list(z["names"])
def curve(key, color, ls, lab):
    i = names.index(key); c_, s_ = z[f"e{i}_c"], z[f"e{i}_s"]
    f1, t1, _ = roc_curve(np.r_[np.zeros(len(c_)), np.ones(len(s_))], np.r_[c_, s_]); ax.plot(f1, t1, color=color, ls=ls, lw=1.3, label=lab)
ax.plot(fpr, tpr, color=INK, lw=1.3, ls="-", label="DEDS | CNN")
curve("DEDS embedder, fine-tuned covers (matched detector)", ORANGE, "-", "DEDS | SPAM (DEDS)")
curve("DEDS embedder, fine-tuned covers (detector trained on S-UNIWARD)", ORANGE, "--", "DEDS | SPAM (S-UNIWARD)")
curve("DEDS embedder, fine-tuned covers (detector trained on LSB matching)", ORANGE, ":", "DEDS | SPAM (LSB matching)")
curve("S-UNIWARD, fine-tuned covers (matched detector)", AQUA, "-", "S-UNIWARD | SPAM (S-UNIWARD)")
ax.plot([0, 1], [0, 1], color="#9aa3ab", lw=0.7, ls=(0, (2, 2)))
ax.set_xlabel("false-positive rate"); ax.set_ylabel("true-positive rate"); ax.set_xlim(0, 1); ax.set_ylim(0, 1.005)
ax.grid(color=GRID, lw=0.5); ax.set_axisbelow(True); ax.set_title("c", loc="left", fontsize=8.5, fontweight="bold"); ax.legend(fontsize=5.4, loc="lower right", handlelength=1.8, borderaxespad=0.4, labelspacing=0.3, title="embedder | detector (trained on)", title_fontsize=5.4)
fig.savefig("../figures/fig4_distortion_detectability.pdf", bbox_inches="tight"); fig.savefig("fig4.png", dpi=160, bbox_inches="tight")
print("done")
